export function personName(rng: Prng, gender: 'female' | 'male'): PersonName {
  const pool = gender === 'female' ? FEMALE_GIVEN : MALE_GIVEN;
  const first = rng.pick(pool);
  let second = rng.pick(pool);
  while (second === first) second = rng.pick(pool);
  const paternal = rng.pick(SURNAMES);
  let maternal = rng.pick(SURNAMES);
  while (maternal === paternal) maternal = rng.pick(SURNAMES);
  return {
    given: rng.chance(0.55) ? [first, second] : [first],
    family: [paternal, maternal],
  };
}

/** Name key used to avoid generating the same full name twice. */
export function nameKey(name: PersonName): string {
  return `${name.given.join(' ')}|${name.family.join(' ')}`;
}
