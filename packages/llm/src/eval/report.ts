import type { Counts, Scores } from './metrics.ts';
import type { Aggregate, EvalRun, EvalSummary } from './run.ts';

const pct = (value: number): string => `${(value * 100).toFixed(1)}%`;
const usd = (value: number): string => `$${value.toFixed(6)}`;
const fmt = (s: Scores): string => `${pct(s.precision)} | ${pct(s.recall)} | ${pct(s.f1)}`;
const tally = (c: Counts): string => `${String(c.tp)} / ${String(c.fp)} / ${String(c.fn)}`;

/** File name for a report: `<date>-<provider>-<model>.md`, model made path-safe. */
export function reportFileName(run: Pick<EvalRun, 'provider' | 'model' | 'startedAt'>): string {
  const date = run.startedAt.toISOString().slice(0, 10);
  const model = run.model.replace(/[^A-Za-z0-9._-]+/g, '_');
  return `${date}-${run.provider}-${model}.md`;
}

function fieldTable(aggregate: Aggregate): string[] {
  return [
    '| Field | Precision | Recall | F1 | TP / FP / FN |',
    '| --- | ---: | ---: | ---: | ---: |',
    `| Conditions (ICD-10 category) | ${fmt(aggregate.scores.conditions)} | ${tally(aggregate.counts.conditions)} |`,
    `| Medications (fuzzy drug name) | ${fmt(aggregate.scores.medications)} | ${tally(aggregate.counts.medications)} |`,
    `| Plan items (kind + due ±20%) | ${fmt(aggregate.scores.planItems)} | ${tally(aggregate.counts.planItems)} |`,
    ...(aggregate.scores.pregnancyOutcome && aggregate.counts.pregnancyOutcome
      ? [
          `| Pregnancy outcome (kind) | ${fmt(aggregate.scores.pregnancyOutcome)} | ${tally(aggregate.counts.pregnancyOutcome)} |`,
        ]
      : []),
    ...(aggregate.scores.pregnancyDating && aggregate.counts.pregnancyDating
      ? [
          `| Pregnancy dating (weeks, LMP, EDD exact) | ${fmt(aggregate.scores.pregnancyDating)} | ${tally(aggregate.counts.pregnancyDating)} |`,
        ]
      : []),
  ];
}

/** Machine-readable summary written next to each report (no note text), read by `eval:compare`. */
export interface ReportSidecar {
  readonly provider: string;
  readonly model: string;
  readonly promptVersion: string;
  readonly startedAt: string;
  readonly dataset: string;
  readonly report: string;
  readonly summary: EvalSummary;
}

export function reportSidecar(run: EvalRun, dataset: string): ReportSidecar {
  return {
    provider: run.provider,
    model: run.model,
    promptVersion: run.promptVersion,
    startedAt: run.startedAt.toISOString(),
    dataset,
    report: reportFileName(run),
    summary: run.summary,
  };
}

/** Side-by-side table of several runs, newest first per provider/model. */
export function renderComparison(runs: readonly ReportSidecar[]): string {
  const rows = [...runs].sort((a, b) => b.startedAt.localeCompare(a.startedAt));
  return [
    '# Note extraction: model comparison',
    '',
    'Generated by `pnpm --filter @follow-up-engine/llm eval:compare` from the JSON summaries in this folder. Same prompt, same post-checks, same gold notes: only the model changes.',
    '',
    '| Date | Provider | Model | Prompt | Gold set | Conditions F1 | Medications F1 | Plan items F1 | hasPlan | Hallucinated quotes | Cost / note | p50 | p95 | Errors |',
    '| --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...rows.map((r) => {
      const o = r.summary.overall;
      return `| ${r.startedAt.slice(0, 10)} | ${r.provider} | [\`${r.model}\`](${r.report}) | ${r.promptVersion} | ${r.dataset} | ${pct(o.scores.conditions.f1)} | ${pct(o.scores.medications.f1)} | ${pct(o.scores.planItems.f1)} | ${pct(o.hasPlanAccuracy)} | ${pct(o.hallucinatedQuoteRate)} | ${usd(r.summary.cost.perNoteUsd)} | ${String(r.summary.latencyMs.p50)} ms | ${String(r.summary.latencyMs.p95)} ms | ${String(o.errors)} |`;
    }),
    '',
  ].join('\n');
}

/** Renders an eval run as a Markdown report. */
export function renderReport(run: EvalRun, notes?: string): string {
  const { summary } = run;
  const { overall } = summary;
  const lines: string[] = [
    `# Note extraction eval: ${run.provider} / ${run.model}`,
    '',
    `- Date: ${run.startedAt.toISOString()}`,
    `- Provider: \`${run.provider}\``,
    `- Model: \`${run.model}\``,
    `- Prompt: \`${run.promptVersion}\``,
    `- Notes: ${String(overall.notes)} (errors: ${String(overall.errors)})`,
    `- Wall time: ${(run.durationMs / 1000).toFixed(1)} s`,
    ...(notes ? [notes] : []),
    '',
    '## Overall',
    '',
    ...fieldTable(overall),
    '',
    '| Metric | Value |',
    '| --- | ---: |',
    `| hasPlan accuracy | ${pct(overall.hasPlanAccuracy)} |`,
    `| Discharge accuracy ("se da de alta", "d/c'd from therapy") | ${pct(overall.dischargeAccuracy)} |`,
    `| Hallucinated-quote rate (items dropped by the verbatim check) | ${pct(overall.hallucinatedQuoteRate)} (${String(overall.quoteRejected)} / ${String(overall.modelItems)}) |`,
    `| Items dropped by the evidence checks (quote in the note but not backing the item) | ${String(overall.evidenceRejected)} / ${String(overall.modelItems)} |`,
    `| Input tokens per note | ${summary.tokens.inputPerNote.toFixed(0)} |`,
    `| Output tokens per note | ${summary.tokens.outputPerNote.toFixed(0)} |`,
    `| Cost per note | ${usd(summary.cost.perNoteUsd)} |`,
    `| Total cost | ${usd(summary.cost.totalUsd)} |`,
    `| Latency p50 | ${String(summary.latencyMs.p50)} ms |`,
    `| Latency p95 | ${String(summary.latencyMs.p95)} ms |`,
    '',
    '## By specialty',
    '',
    '| Specialty | Notes | Conditions F1 | Medications F1 | Plan items F1 | hasPlan acc. | Errors |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...summary.bySpecialty.map(
      (s) =>
        `| ${s.specialty} | ${String(s.notes)} | ${pct(s.scores.conditions.f1)} | ${pct(s.scores.medications.f1)} | ${pct(s.scores.planItems.f1)} | ${pct(s.hasPlanAccuracy)} | ${String(s.errors)} |`,
    ),
    '',
    ...(summary.byLanguage === undefined
      ? []
      : [
          '## By note language',
          '',
          "The language each gold note is written in. The eval never tells the extractor: it detects the language (a stopword count, `language.ts`), reads the note with that language's lexicons, and the detection is scored here.",
          '',
          '| Language | Notes | Detected right | Conditions F1 | Medications F1 | Plan items F1 | hasPlan acc. | Discharge acc. | Errors |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
          ...summary.byLanguage.map(
            (l) =>
              `| ${l.language} | ${String(l.notes)} | ${pct(l.detectionAccuracy)} | ${pct(l.scores.conditions.f1)} | ${pct(l.scores.medications.f1)} | ${pct(l.scores.planItems.f1)} | ${pct(l.hasPlanAccuracy)} | ${pct(l.dischargeAccuracy)} | ${String(l.errors)} |`,
          ),
          '',
          ...summary.byLanguage.flatMap((l) => [`### ${l.language}`, '', ...fieldTable(l), '']),
        ]),
    '## Per note',
    '',
    '| Note | Specialty | Language (read as) | Conditions TP/FP/FN | Medications TP/FP/FN | Plan TP/FP/FN | hasPlan | Quotes dropped | Tokens in/out | Cost | Latency | Error |',
    '| --- | --- | --- | ---: | ---: | ---: | :---: | ---: | ---: | ---: | ---: | --- |',
    ...run.results.map(
      (r) =>
        `| ${r.id} | ${r.specialty} | ${r.language ?? 'es'} (${r.detectedLanguage ?? '?'}) | ${tally(r.counts.conditions)} | ${tally(r.counts.medications)} | ${tally(r.counts.planItems)} | ${r.hasPlanCorrect ? 'ok' : 'wrong'} | ${String(r.quoteRejected)} | ${String(r.inputTokens)}/${String(r.outputTokens)} | ${usd(r.costUsd)} | ${String(r.latencyMs)} ms | ${r.error ?? ''} |`,
    ),
    '',
    '## How to read this',
    '',
    '- Conditions match on the ICD-10 category (first 3 characters). Plan items match on kind and a due date within ±20% of the expected days (at least ±1 day). Medications match on the drug name, allowing two typos.',
    '- Scores are micro-averaged over all items; an empty set (nothing expected, nothing predicted) scores 100%.',
    '- The hallucinated-quote rate counts model items whose evidence quote is not a substring of the note. They never reach the engine: the post-check drops them.',
    '- The evidence checks drop items whose quote is in the note but does not back them: too short ("Plan"), no term linked to the ICD-10 code, no drug name, no plan wording or timing, a denied condition ("niega HTA"), a conditional return ("volver si fiebre"), an interval that contradicts the quoted one, or a measurement listed as a medication.',
    '- Discharge accuracy: the note discharges the patient ("se da de alta") exactly when the gold note says so.',
    '- Pregnancy outcome matches on kind (vaginal, caesarean, loss); an outcome read from obstetric history ("G3P2, cesárea previa") or a planned one is a false positive. Pregnancy dating counts gestational weeks, last menstrual period and estimated delivery date as one item each, matched exactly; dating a note that reports no current pregnancy (a routine "FUM" in an annual control) is a false positive.',
    '- Cost uses the pricing table in `packages/llm/src/pricing.ts`; check it against the vendor before quoting.',
    '',
  ];
  return lines.join('\n');
}
